#!/usr/bin/env node
/**
 * Writes js/site-config.js from content/blog/_data/site.json (+ env overrides).
 * Run before eleventy build (see package.json prebuild).
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const sitePath = path.join(root, "content/blog/_data/site.json");
const outPath = path.join(root, "js/site-config.js");

const site = JSON.parse(fs.readFileSync(sitePath, "utf8"));
const analytics = site.analytics || {};
const consent = site.consent || {};

const config = {
  ga4MeasurementId:
    process.env.ELEVENTY_GA4_ID || analytics.ga4MeasurementId || "",
  cloudflareBeaconToken:
    process.env.ELEVENTY_CF_TOKEN || analytics.cloudflareBeaconToken || "",
  privacyPath: consent.privacyPath || "/blog/privacy/",
  accentColor: consent.accentColor || "#5a7247",
  denyButtonColor: consent.denyButtonColor || "#666666",
};

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(
  outPath,
  `// Generated by scripts/generate-site-config.js — do not edit by hand.\nwindow.PHASE_SHIFT_SITE = ${JSON.stringify(config, null, 2)};\n`,
  "utf8"
);

console.log("Wrote js/site-config.js");
